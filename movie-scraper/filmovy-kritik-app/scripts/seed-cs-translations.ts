async function main() {
  let updated = 0;
  let missing: string[] = [];

  for (const entry of TRANSLATION_REGISTRY) {
    const csValue = CS[entry.key];
    if (!csValue) {
      missing.push(entry.key);
      continue;
    }

    await prisma.translationString.upsert({
      where: { key: entry.key },
      update: { cs: csValue },
      create: { key: entry.key, group: entry.group, sk: entry.sk, cs: csValue }
    });
    updated++;
  }

  console.log(`Hotovo — doplnených ${updated} českých prekladov.`);
  if (missing.length > 0) {
    console.log(`Chýbajúci preklad pre ${missing.length} kľúčov (ostane slovenská verzia):`, missing);
  }
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
